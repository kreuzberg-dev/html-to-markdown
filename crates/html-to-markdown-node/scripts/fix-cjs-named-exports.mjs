// Post-`napi build` fixup for Node ESM interop (issue #450).
//
// `napi build` emits an `index.js` that ends with `module.exports =
// nativeBinding`. Node's ESM loader resolves named imports from a CJS module
// through `cjs-module-lexer`, which only detects statically analyzable
// assignments — a dynamic `module.exports = <runtime object>` exposes nothing,
// so `import { convert } from '@xberg-io/html-to-markdown'` throws "does not
// provide an export named 'convert'".
//
// This appends an explicit `module.exports.<name> = nativeBinding.<name>` line
// for every runtime export declared in `index.d.ts` (functions, enums, consts,
// classes — never type-only `interface`/`type`). Those assignments ARE detected
// by cjs-module-lexer, so named ESM imports resolve while `require()` keeps
// working. The block is delimited by a sentinel and rewritten on every run, so
// it stays correct and idempotent across rebuilds.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const dtsPath = join(packageDir, "index.d.ts");
const jsPath = join(packageDir, "index.js");

const SENTINEL = "// --- BEGIN cjs named re-exports (issue #450, generated by fix-cjs-named-exports.mjs) ---";

const dts = readFileSync(dtsPath, "utf8");
const exportPattern = /^export declare (?:function|enum|const|class)\s+([A-Za-z_$][\w$]*)/gm;
const names = [...dts.matchAll(exportPattern)].map((match) => match[1]);
const uniqueNames = [...new Set(names)];

if (uniqueNames.length === 0) {
  console.error(`fix-cjs-named-exports: no runtime exports found in ${dtsPath}`);
  process.exit(1);
}

let js = readFileSync(jsPath, "utf8");
const sentinelIndex = js.indexOf(SENTINEL);
if (sentinelIndex !== -1) {
  js = js.slice(0, sentinelIndex).replace(/\s+$/, "") + "\n";
}

const reexports = uniqueNames.map((name) => `module.exports.${name} = nativeBinding.${name};`).join("\n");
const block = `\n${SENTINEL}\n${reexports}\n`;

writeFileSync(jsPath, `${js.replace(/\s+$/, "")}\n${block}`);

console.log(`fix-cjs-named-exports: wrote ${uniqueNames.length} named re-export(s) to index.js`);
